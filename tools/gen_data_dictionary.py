"""Generate docs/data_dictionary.md from the built warehouse (column names/types) and dbt YAML descriptions.

    python tools/gen_data_dictionary.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import duckdb
import yaml

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "warehouse" / "tradewar.duckdb"
OUT = ROOT / "docs" / "data_dictionary.md"
SCHEMAS = {"core": "Star schema (dimensions + facts)", "powerbi": "Power BI marts (wide, pre-aggregated)",
           "ml": "Model outputs written back by `python -m ml.run_all`"}


def dbt_descriptions() -> dict[str, tuple[str, dict[str, str]]]:
    out = {}
    for y in (ROOT / "dbt" / "models").rglob("*.yml"):
        doc = yaml.safe_load(y.read_text(encoding="utf-8")) or {}
        for m in doc.get("models", []) or []:
            cols = {c["name"]: c.get("description", "") for c in m.get("columns", []) or []}
            out[m["name"]] = (m.get("description", ""), cols)
        for s in doc.get("sources", []) or []:
            for t in s.get("tables", []) or []:
                cols = {c["name"]: c.get("description", "") for c in t.get("columns", []) or []}
                out[t["name"]] = (t.get("description", ""), cols)
    return out


def pbi_map() -> dict[str, list[str]]:
    src = (ROOT / "powerbi" / "export_for_pbi.py").read_text(encoding="utf-8")
    m: dict[str, list[str]] = {}
    for name, body in re.findall(r'^\s{4}"([^"]+)": \(\s*(?:"""|")(.*?)(?:"""|"),\s*\[', src, flags=re.S | re.M):
        for ref in re.findall(r"\b(?:core|powerbi|ml)\.\w+", body):
            m.setdefault(ref, []).append(name)
    return m


def main() -> None:
    if not DB.exists():
        sys.exit("build the warehouse first (ingest + dbt build + ml.run_all)")
    con = duckdb.connect(str(DB), read_only=True)
    desc, pbi = dbt_descriptions(), pbi_map()
    L = ["# Data dictionary", "",
         "Generated by `python tools/gen_data_dictionary.py` from `warehouse/tradewar.duckdb` (column names and types) and the dbt YAML",
         "descriptions. Units: `_musd` = millions of US dollars, `_pct` = percent, `_pp` = percentage points, `_usd` = US dollars.",
         "Power BI column names are display versions of these (e.g. `imports_musd` -> `Imports $M`; `%` columns become fractions).", ""]
    for schema, title in SCHEMAS.items():
        tables = con.execute("select table_name from information_schema.tables where table_schema = ? order by 1", [schema]).fetchall()
        L += [f"## `{schema}` - {title}", ""]
        for (t,) in tables:
            d, cdesc = desc.get(t, ("", {}))
            rows = con.execute(f'select count(*) from {schema}."{t}"').fetchone()[0]
            L += [f"### `{schema}.{t}`", ""]
            meta = f"{rows:,} rows"
            if f"{schema}.{t}" in pbi:
                meta += " | Power BI table(s): " + ", ".join(f"`{x}`" for x in sorted(set(pbi[f'{schema}.{t}'])))
            L += [(d + "  \n" if d else "") + meta, "", "| column | type | description |", "|---|---|---|"]
            for c, ty in con.execute("select column_name, data_type from information_schema.columns where table_schema = ? and table_name = ? "
                                     "order by ordinal_position", [schema, t]).fetchall():
                L.append(f"| `{c}` | {ty} | {cdesc.get(c, '')} |")
            L.append("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

"""Run every numbered DuckDB analysis in sql/analysis/ against the warehouse and save small outputs.

Usage:  python sql/run_all.py [--db warehouse/tradewar.duckdb] [--max-rows 200]
Outputs: docs/sql_outputs/<query>.csv (first N rows) and docs/sql_outputs/README.md (index).
Exits non-zero if any query fails.
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(ROOT / "warehouse" / "tradewar.duckdb"))
    ap.add_argument("--max-rows", type=int, default=200)
    ap.add_argument("--out", default=str(ROOT / "docs" / "sql_outputs"))
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect(args.db, read_only=True)
    con.execute("set threads=2; set memory_limit='2GB'")
    files = sorted((ROOT / "sql" / "analysis").glob("[0-9][0-9]_*.sql"))
    index, failed = [], []
    for f in files:
        sql = f.read_text(encoding="utf-8")
        title = next((l[2:].strip() for l in sql.splitlines() if l.startswith("--")), f.stem)
        t0 = time.perf_counter()
        try:
            df = con.execute(sql).df()
        except Exception as e:  # noqa: BLE001
            failed.append(f.name)
            print(f"FAIL {f.name}: {e}")
            continue
        ms = (time.perf_counter() - t0) * 1000
        df.head(args.max_rows).to_csv(out / f"{f.stem}.csv", index=False)
        index.append((f.stem, title, len(df), ms))
        print(f"ok   {f.name:<48} {len(df):>5} rows  {ms:7.0f} ms")
    lines = ["# SQL analysis outputs", "", "Generated by `python sql/run_all.py` (first rows of each query).", "",
             "| # | Query | Question | Rows |", "|---|---|---|---|"]
    for stem, title, n, _ in index:
        lines.append(f"| {stem[:2]} | [{stem}]({stem}.csv) | {title} | {n} |")
    (out / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n{len(index)} ok, {len(failed)} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
